                宗旨: 不牟私利、不涉政治、團結鄉親、互助福利、造福社會、發揚
                我鄉親一向優良傳統
            </p>
        </header>

        <main>
            <section class="mb-6">
                <h2 class="section-title">第一條: 本會定名</h2>
                <p class="content-text pl-4">
                    <span class="article-number">饒平鳳凰同鄉會</span>
                </p>
            </section>

            <section class="mb-6">
                <h2 class="section-title">第三條: 會員資格</h2>
                <p class="content-text pl-4">
                    凡屬同鄉及與鄉親有直屬姻親關係者，皆可成為同鄉會成員，姻親會員不得提名正、副會長。
                </p>
            </section>

            <section class="mb-6">
                <h2 class="section-title">第四條: 會員權利</h2>
                <p class="content-text pl-4">
                    有選舉和被選舉權、提議和表決權及優先享有體會各種善舉、義舉之慈普事業。
                </p>
            </section>

            <section class="mb-6">
                <h2 class="section-title">第五條: 會員義務</h2>
                <p class="content-text pl-4">
                    遵守本會各種決議和通告、積極和支持一切會務活動財政寶用。
                </p>
            </section>

            <section class="mb-6">
                <h2 class="section-title">第六條: 福利</h2>
                <p class="content-text pl-4">
                    凡如鄉親有婚慶喜事或新廈落成皆可要求本會理事協助處理，如有父母年老或喪事，本會以橫軸一幅，前往吊祭，若貧窮者，可向本會反映，全體同鄉前往吊祭和協助處理。
                </p>
            </section>

            <section class="mb-6">
                <h2 class="section-title">第七條: 墓限</h2>
                <p class="content-text pl-4">
                    本會墓園地規劃為一等、二等、三等規格。一等地報效本會美金壹仟元、二等地報效本會美金肆佰元、三等地報效本會美金叁佰元，其餘為總地不用報效。若當事人自願樂捐多少不拘，清貧者由同鄉會量情處理之。凡我同鄉人或與同鄉有親屬關係者，皆可安于墓園之原。
                </p>
            </section>

            <section class="mb-6">
                <h2 class="section-title">第八條: 本會經濟</h2>
                <p class="content-text pl-4">
                    本會不收會員費，經濟由樂捐及墓地收入為主，有必要時成員大會發動特別樂捐補助之。
                </p>
            </section>

            <section class="mb-6">
                <h2 class="section-title">第九條: 行政</h2>
                <p class="content-text pl-4">
                    由全體成員大會選出，名譽會長、顧問會長一人、副會長二人、監事一人、文書一人、財政一人、交際一人、福利組長一人、副組長二人，本會成員各家長皆為當然理事，協助會務進行之。
                </p>
            </section>

            <section class="mb-6">
                <h2 class="section-title">第十條: 退會</h2>
                <p class="content-text pl-4">
                    凡有損害、中傷、破壞本會名譽者，經查屬實，初期警告，若不悔改、發動大會表決抵制和取消成員資格。
                </p>
            </section>
        </main>

